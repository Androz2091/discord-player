/** Options for a Discord Player instance and its Remedia client. */
export type DiscordPlayerOptions = Omit<RemediaClientOptions, 'selectNode' | 'botUserId' | 'nodes'> &
  StreamHooks & {
    /** Native nodes; omitted uses a single embedded node without additional configuration. */
    nodes?: RemediaClientOptions['nodes'];

    /** Automatic queue crossfading; disabled by default. Uses PCM decoding and additional processing. */
    crossfade?: CrossfadeOptions;

    /** Authoritative non-bot occupants; null means unavailable and disables emptiness policies.
     * @param guildId Guild identifier.
     * @param channelId Voice channel identifier.
     */
    resolveVoiceChannelUsers?: (guildId: string, channelId: string) => Promise<readonly string[] | null>;

    /** Source registrations initialized with this Player. */
    plugins?: readonly PluginRegistration<any>[];

    /** Legacy metadata probe timeout; audio probing remains extractor-owned. */
    probeTimeout?: number;

    /** Disabled legacy/source IDs. */
    blockExtractors?: readonly string[];
  };

/** Player-level event argument tuples. */
export interface DiscordPlayerEvents extends RemediaClientEvents {
  /** Debug message generated by this Player. */
  debug: [message: string];

  /** Non-fatal Player-level error. */
  error: [error: Error];

  /** Voice state lifecycle event forwarded by an integration adapter. */
  voiceStateUpdate: [guildId: string, event: Record<string, unknown>];
}

/** Familiar Player-level event names. */
export const PlayerEvent = {
  ...RemediaClientEventNames,
  ...PlaybackSessionEvents,
  ...VoiceSessionEvents,
  /** Debug message. */
  debug: 'debug',
  /** Compatibility alias for `debug`. */
  Debug: 'debug',
  /** Player-level error. */
  error: 'error',
  /** Compatibility alias for `error`. */
  Error: 'error',
  /** Voice state update. */
  voiceStateUpdate: 'voiceStateUpdate',
} as const;

/** Player-level event name union. */
export type PlayerEvent = (typeof PlayerEvent)[keyof typeof PlayerEvent];

/** Aggregated counts across the queues owned by a Player. */
export interface DiscordPlayerStatistics {
  /** Number of queues currently cached by this Player. */
  queues: number;

  /** Sum of upcoming tracks across cached queues. */
  upcomingTracks: number;

  /** Number of cached queues with active managed playback. */
  activeQueues: number;
}

/** Familiar OOP Player facade for guild queues and the Remedia client. */
export class DiscordPlayer extends SafeEventEmitter<DiscordPlayerEvents> {
  /** Current package version. */
  static readonly version = packageVersion;

  /** Maximum Gateway dispatches retained while the playback backend starts. */
  private static readonly GATEWAY_BUFFER_LIMIT = 1024;

  /** Shared execution host for modern and legacy sources. */
  public readonly plugins: PluginRegistry;

  /** Legacy constructor-only registration adapter. */
  public readonly extractors: ExtractorExecutionContext;

  /** Source execution independent of queue and voice orchestration. */
  private readonly sources: SourcePluginRuntime;

  private customBackend: PlaybackBackend | null = null;

  private backendInitialization: Promise<void> | null = null;

  private backendReady = false;

  private backendLifetime: AbortSignal | null = null;

  private backendDisposal: Promise<void> | null = null;

  private initialization: Promise<void> | null = null;

  private initializationClientId: string | null = null;

  private backendInitialized = false;

  private backendFailed = false;

  /** Ordered dispatches retained until the selected backend is ready to receive them. */
  private gatewayBuffer: Record<string, unknown>[] = [];

  private gatewayBufferOverflowed = false;

  private initialPlugins: Promise<void>;

  private destruction: Promise<void> | null = null;

  #clientId: string | null = null;

  readonly #lifetimeController = new AbortController();

  /** Lifetime signal, aborted synchronously when destroy() begins, even if cleanup later fails.
   * The signal is stable for this Player and remains aborted after destruction.
   */
  public get signal(): AbortSignal {
    return this.#lifetimeController.signal;
  }

  private detachClientListeners: (() => void) | null = null;

  /** Guild queue manager. */
  public readonly nodes = new GuildNodeManager(this);

  /** Guild queue lifecycle events; separate from Player-level events. */
  public readonly events = new SafeEventEmitter<GuildQueueEventsMap>();

  /** Underlying Remedia client, available after `initialize()`. */
  public remedia: RemediaClient | null = null;

  /** AsyncLocalStorage-backed per-Player command context. */
  public readonly context = new PlayerContext(this);

  /** Optional lyrics lookup through registered capability providers. */
  public readonly lyrics = new Lyrics(this);

  /** Create a Player configured with Remedia client options.
   * @param options Remedia node configurations and the Discord gateway send callback.
   */
  public constructor(
    /** Remedia node configurations and Discord gateway send callback. */
    public readonly options: DiscordPlayerOptions,
  ) {
    super();

    this.sources = new SourcePluginRuntime({ player: this });
    this.plugins = this.sources.plugins;
    installLocalCapabilities(this.plugins);
    this.plugins.defineProvider('playback.backend');
    this.extractors = this.sources.extractors;

    this.initialPlugins = Promise.all((options.plugins ?? []).map((plugin) => this.plugins.register(plugin))).then(
      () => {
        try {
          this.plugins.executeSync('player.ready', { playerId: this.id });
        } catch (error) {
          this.emit('error', error instanceof Error ? error : new Error(String(error)));
        }
      },
    );

    // Retain the rejection for initialize/search while preventing an unobserved constructor promise.
    void this.initialPlugins.catch(() => undefined);
    registerPlayer(this);
  }

  /** Await constructor registrations and discover configured advanced HTTP hosts.
   * @internal
   */
  public async ready(): Promise<void> {
    this.signal.throwIfAborted();
    await this.initialPlugins;
    await this.plugins.ready();
  }

  /** Identifier of this Player instance. */
  public readonly id = randomUUID();

  /** Version string for this package build. */
  public get version(): string {
    return DiscordPlayer.version;
  }

  /** Aggregated queue and runtime statistics. */
  public get statistics(): DiscordPlayerStatistics {
    const queues = Array.from(this.nodes.cache.values());

    return {
      queues: queues.length,
      upcomingTracks: queues.reduce((sum, queue) => sum + queue.size, 0),
      activeQueues: queues.reduce((sum, queue) => sum + Number(queue.isPlaying()), 0),
    };
  }

  /** Return Remedia node snapshots after initialization. */
  public get nodeSnapshots() {
    return this.getRemedia(false)?.nodes ?? null;
  }

  /** Get the Remedia client or return null when `throwOnMissing` is false.
   * @returns The initialized Remedia client, or null when optional lookup is requested before initialization.
   */
  public getRemedia(): RemediaClient;

  /** Get the Remedia client or return null when `throwOnMissing` is false.
   * @param throwOnMissing Whether to throw when Remedia is not initialized.
   * @returns The initialized Remedia client, or null when optional lookup is requested before initialization.
   */
  public getRemedia(throwOnMissing: false): RemediaClient | null;

  /** Get the Remedia client or return null when `throwOnMissing` is false.
   * @param throwOnMissing Whether to throw when Remedia is not initialized.
   * @returns The initialized Remedia client, or null when optional lookup is requested before initialization.
   */
  public getRemedia(throwOnMissing = true): RemediaClient | null {
    if (this.customBackend) {
      if (throwOnMissing) throw new Error('A custom playback backend is active. Use player.getBackend().');
      return null;
    }
    if (!this.remedia && throwOnMissing) {
      throw new Error('RemediaClient is not initialized. Call player.initialize(clientId) first.');
    }

    return this.remedia;
  }

  /** Initialize Remedia and associate this Player with the bot user ID.
   * @param clientId Discord bot user snowflake used for remote node identity.
   */
  public initialize(clientId: string): Promise<void> {
    this.plugins.assertNotDispatching();
    this.signal.throwIfAborted();
    if (this.backendDisposal && this.backendInitialized)
      return Promise.reject(new Error('Playback backend has been disposed. Create a new Player.'));
    if (this.initialization && this.initializationClientId !== clientId)
      return Promise.reject(new Error('Player initialization already started for a different clientId.'));
    this.initializationClientId = clientId;
    return (this.initialization ??= this.initializeBackend(clientId));
  }

  /** Access the initialized custom provider or the default Remedia client.
   * @returns Active playback implementation. Throws before initialization or after disposal.
   */
  public getBackend(): PlaybackBackend | RemediaClient {
    const backend = this.customBackend ?? this.remedia;
    if (!backend || (this.customBackend && !this.backendReady) || this.playbackSignal.aborted || this.backendDisposal)
      throw new Error('Playback backend is not active.');
    return backend;
  }

  /** Active advanced provider, or null for default Remedia execution.
   * @internal
   */
  public get playbackBackend(): PlaybackBackend | null {
    return this.customBackend;
  }

  /** Playback provider lifetime, combined with Player cancellation. @internal */
  public get playbackSignal(): AbortSignal {
    return this.backendLifetime ?? this.signal;
  }

  private disposeCustomBackend(): Promise<void> {
    if (this.backendDisposal) return this.backendDisposal;
    const backend = this.customBackend;
    if (!backend) return Promise.resolve();
    this.backendReady = false;
    this.backendFailed = true;
    this.clearGatewayBuffer();
    this.backendDisposal = (async () => {
      const errors: unknown[] = [];
      try {
        await this.nodes.clear();
      } catch (error) {
        errors.push(error);
      }
      await this.backendInitialization?.catch(() => undefined);
      try {
        await backend.destroy();
      } catch (error) {
        errors.push(error);
      }
      this.customBackend = null;
      this.#clientId = null;
      if (errors.length) throw new AggregateError(errors, 'Playback backend cleanup failed');
    })();
    return this.backendDisposal;
  }

  private async initializeBackend(
    /** Discord bot user snowflake used for remote node identity. */
    clientId: string,
  ): Promise<void> {
    try {
      await this.ready();
      this.signal.throwIfAborted();
    } catch (error) {
      try {
        await this.plugins.destroy();
      } catch (cleanup) {
        throw new AggregateError([error, cleanup], 'Plugin initialization and cleanup failed', { cause: cleanup });
      }

      throw error;
    }

    const initialization = intercept(this.plugins, 'player.beforeInitialize', { playerId: this.id, clientId });
    if (initialization.playerId !== this.id || typeof initialization.clientId !== 'string' || !initialization.clientId)
      throw new TypeError('Invalid Player initialization identity.');
    clientId = initialization.clientId;
    this.#clientId = clientId;
    const backend = this.plugins.selectProvider('playback.backend', () => this.disposeCustomBackend());
    if (backend) {
      this.customBackend = backend;
      const registrationSignal = this.plugins.providerSignal('playback.backend');
      this.backendLifetime = registrationSignal ? AbortSignal.any([this.signal, registrationSignal]) : this.signal;
      try {
        if (
          !backend.id ||
          !Array.isArray(backend.capabilities?.sources) ||
          !backend.capabilities.sources.every((kind) =>
            ['url', 'file', 'buffer', 'stream', 'operation'].includes(kind),
          ) ||
          typeof backend.capabilities.crossfade !== 'boolean' ||
          typeof backend.capabilities.filters !== 'boolean' ||
          (backend.capabilities.pluginHosts !== undefined &&
            (!Array.isArray(backend.capabilities.pluginHosts) ||
              !backend.capabilities.pluginHosts.every((host) => typeof host === 'string' && host.length > 0))) ||
          !['initialize', 'receive', 'createSession', 'destroy'].every(
            (name) => typeof Reflect.get(backend, name) === 'function',
          )
        )
          throw new TypeError('Invalid playback backend implementation.');
        this.backendInitialization = Promise.resolve().then(() =>
          backend.initialize({ clientId, signal: this.playbackSignal, send: this.options.send }),
        );
        await this.backendInitialization;
        this.playbackSignal.throwIfAborted();
        if (this.backendDisposal) throw new Error('Playback provider was removed during initialization.');
        this.backendReady = true;
        this.backendInitialized = true;
        this.replayGateway();
        try {
          this.plugins.executeSync('player.initialized', { playerId: this.id });
        } catch (error) {
          this.emit('error', error instanceof Error ? error : new Error(String(error)));
        }
        return;
      } catch (error) {
        this.backendFailed = true;
        this.clearGatewayBuffer();
        const errors: unknown[] = [error];
        try {
          await this.disposeCustomBackend();
        } catch (cleanup) {
          errors.push(cleanup);
        }
        try {
          await this.plugins.destroy();
        } catch (cleanup) {
          errors.push(cleanup);
        }
        if (errors.length > 1)
          throw new AggregateError(errors, 'Playback backend initialization and cleanup failed', { cause: error });
        throw error;
      }
    }

    const {
      resolveVoiceChannelUsers: _resolver,
      onBeforeCreateStream: _before,
      onStreamExtracted: _extracted,
      onAfterCreateStream: _after,
      crossfade: _crossfade,
      plugins: _plugins,
      blockExtractors: _blocked,
      probeTimeout: _probeTimeout,
      ...remediaOptions
    } = this.options;

    try {
      const client = await RemediaClient.create({
        ...remediaOptions,
        nodes: remediaOptions.nodes ?? [{ id: 'local', type: 'embedded' }],
        botUserId: clientId,
      });
      if (this.signal.aborted) {
        await client.close();
        this.signal.throwIfAborted();
      }
      this.remedia = client;
      this.backendInitialized = true;
      this.clearGatewayBuffer();
      this.attachClientListeners(client);
      try {
        this.plugins.executeSync('player.initialized', { playerId: this.id });
      } catch (error) {
        this.emit('error', error instanceof Error ? error : new Error(String(error)));
      }
    } catch (error) {
      this.#clientId = null;
      this.backendFailed = true;
      this.clearGatewayBuffer();

      try {
        await this.plugins.destroy();
      } catch (cleanup) {
        throw new AggregateError([error, cleanup], 'Player initialization and plugin cleanup failed', {
          cause: cleanup,
        });
      }

      throw error;
    }
  }

  private attachClientListeners(client: RemediaClient): void {
    this.detachClientListeners?.();

    const cleanups: (() => void)[] = [];
    type ClientListener = <Name extends keyof RemediaClientEvents>(
      name: Name,
      handler: (...args: RemediaClientEvents[Name]) => void,
    ) => void;

    // Narrow Node's open EventEmitter overloads to the installed native contract.
    const subscribe = client.on.bind(client) as ClientListener;
    const unsubscribe = client.off.bind(client) as ClientListener;
    const on: ClientListener = (name, handler) => {
      subscribe(name, handler);
      cleanups.push(() => unsubscribe(name, handler));
    };
    const emit = this.emit.bind(this) as <Name extends keyof RemediaClientEvents>(
      name: Name,
      ...args: RemediaClientEvents[Name]
    ) => boolean;
    const forward = <Name extends keyof RemediaClientEvents>(name: Name) => {
      on(name, (...args) => emit(name, ...args));
    };

    for (const name of Object.values({ ...RemediaClientEventNames, ...PlaybackSessionEvents, ...VoiceSessionEvents })) {
      forward(name);
    }

    for (const name of ['sessionResumed', 'sessionLost'] as const) {
      on(name, (event) => {
        for (const guildId of event.guildIds) this.nodes.get(guildId)?.emit(name, event);
      });
    }

    for (const name of ['guildAssigned', 'guildReleased'] as const) {
      on(name, (event) => this.nodes.get(event.guildId)?.emit(name, event));
    }

    on('guildMigrated', (event) => this.nodes.get(event.guildId)?.emit('guildMigrated', event));

    this.detachClientListeners = () => {
      for (const cleanup of cleanups) cleanup();
    };
  }

  /** Get the initialized Discord bot user ID.
   * @returns The bot's Discord user ID.
   */
  public getClientId(): string {
    if (!this.#clientId) {
      throw new Error('Player client ID is not initialized. Call player.initialize(clientId) first.');
    }

    return this.#clientId;
  }

  /** Forward every raw Discord Gateway dispatch to the active playback backend and track queue voice states.
   *
   * The active backend needs the complete dispatch stream, including `READY`, to track Gateway sessions and
   * dispatch ordering; do not filter packets before calling this method. Dispatches received before the selected
   * backend is ready are retained in order so a custom provider still observes initial Gateway state. Discord
   * Player separately consumes `VOICE_STATE_UPDATE` for queue voice policies. Packets are ignored after `destroy()`.
   * @param payload Raw Gateway dispatch packet from the Discord client's event adapter.
   */
  public receive(
    /** Raw Gateway dispatch packet from the Discord client's event adapter. */
    payload: Record<string, unknown>,
  ): void {
    if (this.playbackSignal.aborted || this.backendDisposal) return;

    if (!this.backendInitialized) {
      this.bufferGateway(payload);
      return;
    }

    this.dispatchGateway(payload);
  }

  private bufferGateway(payload: Record<string, unknown>): void {
    if (this.backendFailed) return;

    if (this.gatewayBuffer.length >= DiscordPlayer.GATEWAY_BUFFER_LIMIT) {
      if (!this.gatewayBufferOverflowed) {
        this.gatewayBufferOverflowed = true;
        this.emit(
          'debug',
          `Discord Player dropped Gateway dispatches beyond the ${DiscordPlayer.GATEWAY_BUFFER_LIMIT}-packet pre-initialization buffer.`,
        );
      }
      return;
    }

    this.gatewayBuffer.push(payload);
  }

  private replayGateway(): void {
    const buffered = this.gatewayBuffer;

    this.gatewayBuffer = [];
    this.gatewayBufferOverflowed = false;

    for (const payload of buffered) this.dispatchGateway(payload);
  }

  private clearGatewayBuffer(): void {
    this.gatewayBuffer = [];
    this.gatewayBufferOverflowed = false;
  }

  private dispatchGateway(payload: Record<string, unknown>): void {
    const backend = this.customBackend ?? this.remedia;
    if (!backend) return;

    backend.receive(payload);

    if (
      payload.t === 'VOICE_STATE_UPDATE' &&
      payload.d &&
      typeof payload.d === 'object' &&
      'guild_id' in payload.d &&
      typeof payload.d.guild_id === 'string'
    ) {
      this.emit('voiceStateUpdate', payload.d.guild_id, payload);
      this.nodes.get(payload.d.guild_id)?.voice.receive(payload);
    }
  }

  /** Convert a supported in-memory media object to a SearchResult. Search strings require a source plugin.
   * @param query Track, Playlist, SearchResult, Track array, or query string.
   * @param options Source targeting, requester, and cancellation.
   * @returns A SearchResult, empty when no source plugin handled a query string.
   */
  public async search(
    /** Track, Playlist, SearchResult, Track array, or query string. */
    query: MediaResource,
    /** Source targeting, requester, and cancellation. */
    options: SearchOptions = {},
  ): Promise<SearchResult> {
    options.signal?.throwIfAborted();

    if (typeof query === 'string') await this.ready();
    if (options.hostId && !this.plugins.hasHost(options.hostId))
      throw new Error(`Source host ${options.hostId} is not configured`);

    return this.sources.search(query, {
      ...options,
      signal: options.signal ? AbortSignal.any([this.signal, options.signal]) : this.signal,
    });
  }

  /** Select a source for the assigned audio node without opening remote media in the bot.
   * @internal
   * @param track Queued canonical Track.
   * @param nodeId Assigned Remedia node ID.
   * @param signal Playback preparation lifetime.
   * @param queue Optional queue supplying resource hooks and async context.
   * @returns Native operation descriptor for remote hosts, otherwise the local resolver result.
   */
  public async resolvePlaybackSource(
    track: Track,
    nodeId: string | null,
    signal: AbortSignal,
    queue?: GuildQueue,
  ): Promise<MediaSource> {
    signal.throwIfAborted();

    const node = this.getRemedia(false)?.nodes.find((item) => item.id === nodeId);
    if (queue)
      return prepareResource(
        queue,
        track,
        signal,
        this.customBackend
          ? !this.customBackend.capabilities.sources.some((kind) => kind === 'stream' || kind === 'buffer')
          : node?.type !== 'embedded',
        () => this.resolveSourceDescriptor(track, nodeId, signal, queue.guildId),
      );

    return this.resolveSourceDescriptor(track, nodeId, signal, null);
  }

  private async resolveSourceDescriptor(
    track: Track,
    nodeId: string | null,
    signal: AbortSignal,
    guildId: string | null,
  ): Promise<MediaSource> {
    signal.throwIfAborted();
    const node = this.getRemedia(false)?.nodes.find((item) => item.id === nodeId);
    const hostId = track.sourceReference?.hostId;

    if (hostId) {
      if (!this.plugins.hasHost(hostId)) throw new Error(`Source host ${hostId} is not configured`);

      if (!track.sourceReference?.pluginId) throw new Error('Remote Track has no provider identity');

      if (this.options.blockExtractors?.includes(track.sourceReference.pluginId))
        throw new Error('Track provider is blocked');

      if (
        this.customBackend
          ? !this.customBackend.capabilities.sources.includes('operation') ||
            !this.customBackend.capabilities.pluginHosts?.includes(hostId)
          : node?.type !== 'remote' ||
            !node.capabilities?.pluginOperations?.available ||
            !node.capabilities.pluginOperations.hosts.includes(hostId)
      )
        throw new Error(`Playback backend cannot access source host ${hostId}`);

      const source: OperationMediaSource = {
        hostId,
        pluginId: SOURCE_PLUGIN_ID,
        operation: 'source.stream',
        input: { track: serializeSourceTrack(track) },
      };

      if (!this.plugins.hasCapability('media.descriptor')) return source;
      const descriptor = await this.plugins.execute('media.descriptor', { source, guildId }, { signal });
      if (
        !descriptor ||
        !descriptor.source ||
        !('hostId' in descriptor.source) ||
        descriptor.source.hostId !== hostId ||
        descriptor.source.pluginId !== source.pluginId ||
        descriptor.source.operation !== source.operation
      )
        throw new TypeError('Remote descriptor interception must preserve source host identity.');
      return descriptor.source;
    }

    return this.plugins.resolveStream(track, {
      guildId,
      signal,
      remote: this.customBackend
        ? !this.customBackend.capabilities.sources.some((kind) => kind === 'stream' || kind === 'buffer')
        : node?.type !== 'embedded',
      blocked: this.options.blockExtractors,
    });
  }

  /** Resolve a structural channel, create its guild queue, and delegate playback to `queue.play()`.
   * @param channel Voice channel object, channel ID, or explicit `{guildId, channelId}` pair.
   * @param resource Resource to search or play.
   * @param options Queue defaults and queue-managed playback options.
   * @returns The queue, selected Track, immediate Remedia result, and search result.
   */
  public async play<Metadata = unknown>(
    /** Voice channel object, channel ID, or explicit `{guildId, channelId}` pair. */
    channel: PlayerChannelResolvable,
    /** Resource to search or play. */
    resource: MediaResource,
    /** Queue defaults and queue-managed playback options. */
    options: PlayerPlayOptions<Metadata> = {},
  ): Promise<PlayerNodeInitializationResult<Metadata>> {
    const channelId = typeof channel === 'string' ? channel : 'channelId' in channel ? channel.channelId : channel.id;
    const inferredGuildId =
      typeof channel === 'string'
        ? undefined
        : 'channelId' in channel
          ? channel.guildId
          : (channel.guildId ?? channel.guild?.id);
    const guildId = options.guildId ?? inferredGuildId;

    if (!guildId) {
      throw new TypeError('A guildId is required when channel does not expose a structural guild reference.');
    }

    const queueDefaults = options.nodeOptions ?? {};
    const queue = await this.nodes.create<Metadata>(guildId, queueDefaults);
    const searchResult = await this.search(resource, options);

    if (searchResult.isEmpty()) {
      return { queue, resource, searchResult, track: null, playerResult: null };
    }

    const { nodeOptions: _nodeOptions, guildId: _guildId, ...playOptions } = options;
    const result = await queue.play(searchResult, {
      ...playOptions,
      channelId,
    });

    return { queue, resource, searchResult, ...result };
  }

  /** Get an existing guild queue.
   * @param guildId Guild ID to resolve.
   * @returns The cached queue, or null when no queue exists.
   */
  public getQueue<Metadata = unknown>(
    /** Guild ID to resolve. */
    guildId: string,
  ) {
    return this.nodes.get<Metadata>(guildId);
  }

  /** Get or create a guild queue.
   * @param guildId Guild ID to resolve.
   * @param options Queue defaults used only when the queue is first created.
   * @returns The existing or newly created queue.
   */
  public createQueue<Metadata = unknown>(
    /** Guild ID to resolve. */
    guildId: string,
    /** Queue defaults used only when the queue is first created. */
    options: GuildQueueOptions<Metadata> = {},
  ) {
    return this.nodes.create(guildId, options);
  }

  /** Destroy this Player's queue for a guild ID.
   * @param guildId Guild ID whose queue should be destroyed.
   * @returns Whether a cached queue existed and was destroyed.
   */
  public deleteQueue(
    /** Guild ID whose queue should be destroyed. */
    guildId: string,
  ): Promise<boolean> {
    return this.nodes.delete(guildId);
  }

  /** Abort the Player lifetime signal, then destroy all managed queues and plugins. */
  public destroy(): Promise<void> {
    if (this.destruction) return this.destruction;
    this.plugins.assertNotDispatching();
    this.clearGatewayBuffer();
    this.destruction = Promise.resolve().then(async () => {
      const errors: unknown[] = [];
      try {
        this.plugins.executeSync('player.destroying', { playerId: this.id });
      } catch (error) {
        errors.push(error);
      }
      try {
        await queueCleanup;
      } catch (error) {
        errors.push(error);
      }
      try {
        if (this.customBackend || this.backendDisposal) await this.disposeCustomBackend();
        else await this.remedia?.close();
      } catch (error) {
        errors.push(error);
      }
      try {
        await this.plugins.destroy();
      } catch (error) {
        errors.push(error);
      }
      this.detachClientListeners?.();
      this.detachClientListeners = null;
      this.remedia = null;
      this.#clientId = null;
      if (errors.length === 1) throw errors[0];
      if (errors.length) throw new AggregateError(errors, 'Player resource cleanup failed');
    });
    unregisterPlayer(this);
    this.#lifetimeController.abort();
    // Begin queue lifetime cancellation synchronously; teardown still shares each queue's promise.
    const queueCleanup = this.nodes.clear();
    return this.destruction;
  }

  /** Emit a Player-level debug message.
   * @param message Message to publish.
   */
  public debug(
    /** Message to publish. */
    message: string,
  ): void {
    this.emit('debug', message);
  }
}

