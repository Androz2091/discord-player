import { EventEmitter } from 'node:events';
import { RemediaClient, type RemediaClientOptions } from '@remedia/client';
import { GuildQueueManager } from './managers/guild-queue.manager.js';
import type { GuildQueueEventsMap } from './structures/common/guild-queue-events.js';
import { randomInt } from 'node:crypto';
import type {
  MediaResource,
  PlayerNodeInitializationOptions,
  PlayerNodeInitializationResult,
  SearchOptions,
} from './types.js';
import { Track } from './structures/track.js';
import { Playlist } from './structures/playlist.js';
import { SearchResult } from './structures/search-result.js';

export interface DiscordPlayerOptions extends Omit<RemediaClientOptions, 'selectNode' | 'botUserId'> {}

export interface DiscordPlayerEvents {
  /**
   * Emitted when a debug message is generated by the DiscordPlayer instance.
   * @param message The debug message string.
   */
  debug: [message: string];
}

export class DiscordPlayer extends EventEmitter<DiscordPlayerEvents> {
  #clientId: string | null = null;
  /**
   * The GuildQueueManager instance responsible for managing guild queues within this DiscordPlayer instance.
   */
  public queues: GuildQueueManager = new GuildQueueManager(this);
  /**
   * The GuildQueue lifecycle events channel for this DiscordPlayer instance.
   */
  public events: EventEmitter<GuildQueueEventsMap> = new EventEmitter();
  /**
   * The underlying RemediaClient instance used for handling audio streaming and node management.
   */
  public remedia: RemediaClient | null = null;

  /**
   * Creates a new instance of the DiscordPlayer class.
   * @param options The options to configure the DiscordPlayer instance, excluding the selectNode and botUserId properties.
   */
  public constructor(private readonly options: DiscordPlayerOptions) {
    super();
  }

  /**
   * Returns the list of available remedia nodes managed by the underlying RemediaClient instance.
   * @returns An array of remedia nodes, or null if the RemediaClient is not initialized.
   */
  public get nodes() {
    return this.getRemedia(false)?.nodes ?? null;
  }

  /**
   * Returns the underlying RemediaClient instance used by the DiscordPlayer.
   * @param force when true, it throws an error if the RemediaClient is not initialized. When false, it returns null if not initialized.
   * @returns The RemediaClient instance.
   */
  public getRemedia(): RemediaClient;
  public getRemedia(force: false): RemediaClient | null;
  public getRemedia(force = true): RemediaClient | null {
    if (!this.remedia && force) {
      throw new Error('RemediaClient is not initialized. Please call <DiscordPlayer>.initialize() first.');
    }

    return this.remedia;
  }

  /**
   * Initializes the DiscordPlayer internals.
   * @param clientId The client id of the Discord bot user to be associated with this DiscordPlayer instance.
   * @example // discord.js example
   * client.once(Events.ClientReady, async (client) => {
   *   await player.initialize(client.user.id);
   * });
   */
  public async initialize(clientId: string): Promise<void> {
    this.#clientId = clientId;
    this.remedia = await RemediaClient.create({
      ...this.options,
      botUserId: clientId,
      selectNode: async (nodes, context) => {
        const queue = this.queues.get(context.guildId);
        if (!queue) {
          throw new Error(`[NodeSelectionError] No guild queue found for guild ID: ${context.guildId}`);
        }

        if (!queue.options.selectNode) {
          // TODO: capacity-aware node selection strategy
          const selected = nodes[randomInt(0, nodes.length)];
          if (!selected) {
            throw new Error(`[NodeSelectionError] No nodes available for selection in guild ID: ${context.guildId}`);
          }

          return selected.id;
        }

        return queue.options.selectNode(nodes, context);
      },
    });
  }

  public getClientId(): string {
    if (!this.#clientId) {
      throw new Error(
        'DiscordPlayer client ID is not initialized. Please call <DiscordPlayer>.initialize(clientId) first.',
      );
    }

    return this.#clientId;
  }

  /**
   * Receives gateway voice payloads and forwards them to the underlying RemediaClient for processing.
   * @param payload The gateway voice payload to be processed.
   * @example // discord.js example
   * client.on(Events.Raw, (payload) => player.receive(payload));
   */
  public receive(payload: Record<string, unknown>): void {
    if (!this.remedia || !('t' in payload) || typeof payload.t !== 'string') {
      return;
    }

    // ignore non-voice payloads to avoid unnecessary processing
    if (!['VOICE_STATE_UPDATE', 'VOICE_SERVER_UPDATE'].includes(payload.t)) {
      return;
    }

    return this.getRemedia(false)?.receive(payload);
  }

  public async search(query: MediaResource, options: SearchOptions = {}): Promise<SearchResult> {
    void options; // TODO: implement search options
    if (query instanceof SearchResult) return query;

    if (query instanceof Track) {
      return new SearchResult({
        tracks: [query],
        playlist: null,
      });
    }

    if (query instanceof Playlist) {
      return new SearchResult({
        tracks: query.tracks,
        playlist: query,
      });
    }

    return SearchResult.empty();
  }

  public async play<T = any>(
    resource: MediaResource,
    options: PlayerNodeInitializationOptions<T>,
  ): Promise<PlayerNodeInitializationResult<T>> {
    const queue = await this.queues.create(options.guildId, options.nodeOptions);
    const searchResult = await this.search(resource, options.searchOptions);

    if (!searchResult) {
      return {
        queue,
        resource,
        searchResult,
        playerResult: null,
      };
    }

    const session = queue.node.getSession(false);

    using _lock = await queue.tasks.acquire('player.queue.play');

    if (!session || session.channelId !== options.channelId || (options.nodeId && session.nodeId !== options.nodeId)) {
      await queue.connect({
        channelId: options.channelId,
        nodeId: options.nodeId,
      });
    }

    if (resource instanceof Track) {
      queue.addTrack(resource);
    } else if (resource instanceof Playlist) {
      queue.addTracks(resource.tracks);
    } else {
      throw new Error('Invalid media resource provided. Only Track and Playlist objects are supported at the moment.');
    }

    if (!queue.isPlaying()) {
      const result = await queue.node.play(null, options.audioPlayerOptions);

      return {
        queue,
        resource,
        playerResult: result,
        searchResult,
      };
    } else {
      return {
        queue,
        resource,
        playerResult: null,
        searchResult,
      };
    }
  }
}
