const packageVersion = (createRequire(import.meta.url)('../package.json') as { version: string }).version;

/** Options for a Discord Player instance and its Remedia client. */
export type DiscordPlayerOptions = Omit<RemediaClientOptions, 'selectNode' | 'botUserId'> & {
  /** Automatic queue crossfading; disabled by default. Uses PCM decoding and additional processing. */
  crossfade?: CrossfadeOptions;

  /** Standalone HTTP source deployments, searched in order after local sources decline. */
  sourceHosts?: readonly RemoteSourceHostOptions[];

  /** Source registrations initialized with this Player. */
  plugins?: readonly PluginRegistration<any>[];

  /** Legacy metadata probe timeout; audio probing remains extractor-owned. */
  probeTimeout?: number;

  /** Disabled legacy/source IDs. */
  blockExtractors?: readonly string[];
};

/** Player-level event argument tuples. */
export interface DiscordPlayerEvents extends RemediaClientEvents {
  /** Debug message generated by this Player. */
  debug: [message: string];

  /** Non-fatal Player-level error. */
  error: [error: Error];

  /** Voice state lifecycle event forwarded by an integration adapter. */
  voiceStateUpdate: [guildId: string, event: unknown];
}

/** Familiar Player-level event names. */
export const PlayerEvent = {
  ...RemediaClientEventNames,
  ...PlaybackSessionEvents,
  ...VoiceSessionEvents,
  /** Debug message. */
  debug: 'debug',
  /** Compatibility alias for `debug`. */
  Debug: 'debug',
  /** Player-level error. */
  error: 'error',
  /** Compatibility alias for `error`. */
  Error: 'error',
  /** Voice state update. */
  voiceStateUpdate: 'voiceStateUpdate',
} as const;

/** Player-level event name union. */
export type PlayerEvent = (typeof PlayerEvent)[keyof typeof PlayerEvent];

/** Aggregated counts across the queues owned by a Player. */
export interface DiscordPlayerStatistics {
  /** Number of queues currently cached by this Player. */
  queues: number;

  /** Sum of upcoming tracks across cached queues. */
  upcomingTracks: number;

  /** Number of cached queues with active managed playback. */
  activeQueues: number;
}

/** Familiar OOP Player facade for guild queues and the Remedia client. */
export class DiscordPlayer extends SafeEventEmitter<DiscordPlayerEvents> {
  /** Current package version. */
  static readonly version = packageVersion;

  /** Shared execution host for modern and legacy sources. */
  public readonly plugins: PluginRegistry;

  /** Legacy constructor-only registration adapter. */
  public readonly extractors: ExtractorExecutionContext;

  /** Source execution independent of queue and voice orchestration. */
  public readonly sources: SourcePluginRuntime;

  private readonly remoteSources: RemoteSourceHosts;

  private initialPlugins: Promise<void>;

  #clientId: string | null = null;

  readonly #lifetimeController = new AbortController();

  /** Lifetime signal, aborted synchronously when destroy() begins, even if cleanup later fails.
   * The signal is stable for this Player and remains aborted after destruction.
   */
  public get signal(): AbortSignal {
    return this.#lifetimeController.signal;
  }

  private detachClientListeners: (() => void) | null = null;

  /** Guild queue manager. */
  public readonly queues = new GuildQueueManager(this);

  /** Compatibility alias for the v7 `player.nodes` GuildNodeManager. */
  public get nodes(): GuildQueueManager {
    return this.queues;
  }

  /** Guild queue lifecycle events; separate from Player-level events. */
  public readonly events = new SafeEventEmitter<GuildQueueEventsMap>();

  /** Underlying Remedia client, available after `initialize()`. */
  public remedia: RemediaClient | null = null;

  /** AsyncLocalStorage-backed per-Player command context. */
  public readonly context = new PlayerContext(this);

  /** LRCLIB lyrics search and lookup client. */
  public readonly lyrics = new LrcLib(this);

  /** Create a Player configured with Remedia client options.
   * @param options Remedia node configurations and the Discord gateway send callback.
   */
  public constructor(
    /** Remedia node configurations and Discord gateway send callback. */
    public readonly options: DiscordPlayerOptions,
  ) {
    super();

    this.remoteSources = new RemoteSourceHosts(options.sourceHosts ?? []);
    this.sources = new SourcePluginRuntime({ player: this });
    this.plugins = this.sources.plugins;
    this.extractors = this.sources.extractors;

    this.initialPlugins = Promise.all((options.plugins ?? []).map((plugin) => this.plugins.register(plugin))).then(
      () => undefined,
    );

    // Retain the rejection for initialize/search while preventing an unobserved constructor promise.
    void this.initialPlugins.catch(() => undefined);
    registerPlayer(this);
  }

  /** Identifier of this Player instance. */
  public readonly id = randomUUID();

  /** Version string for this package build. */
  public get version(): string {
    return DiscordPlayer.version;
  }

  /** Aggregated queue and runtime statistics. */
  public get statistics(): DiscordPlayerStatistics {
    const queues = Array.from(this.queues.cache.values());

    return {
      queues: queues.length,
      upcomingTracks: queues.reduce((sum, queue) => sum + queue.size, 0),
      activeQueues: queues.reduce((sum, queue) => sum + Number(queue.isPlaying()), 0),
    };
  }

  /** Return Remedia node snapshots after initialization. */
  public get nodeSnapshots() {
    return this.getRemedia(false)?.nodes ?? null;
  }

  /** Get the Remedia client or return null when `throwOnMissing` is false.
   * @returns The initialized Remedia client, or null when optional lookup is requested before initialization.
   */
  public getRemedia(): RemediaClient;

  /** Get the Remedia client or return null when `throwOnMissing` is false.
   * @param throwOnMissing Whether to throw when Remedia is not initialized.
   * @returns The initialized Remedia client, or null when optional lookup is requested before initialization.
   */
  public getRemedia(throwOnMissing: false): RemediaClient | null;

  /** Get the Remedia client or return null when `throwOnMissing` is false.
   * @param throwOnMissing Whether to throw when Remedia is not initialized.
   * @returns The initialized Remedia client, or null when optional lookup is requested before initialization.
   */
  public getRemedia(throwOnMissing = true): RemediaClient | null {
    if (!this.remedia && throwOnMissing) {
      throw new Error('RemediaClient is not initialized. Call player.initialize(clientId) first.');
    }

    return this.remedia;
  }

  /** Initialize Remedia and associate this Player with the bot user ID.
   * @param clientId Discord bot user snowflake used for remote node identity.
   */
  public async initialize(
    /** Discord bot user snowflake used for remote node identity. */
    clientId: string,
  ): Promise<void> {
    try {
      await this.initialPlugins;
      await this.plugins.ready();
    } catch (error) {
      try {
        await this.plugins.destroy();
      } catch (cleanup) {
        throw new AggregateError([error, cleanup], 'Plugin initialization and cleanup failed', { cause: cleanup });
      }

      throw error;
    }

    this.#clientId = clientId;

    const {
      crossfade: _crossfade,
      sourceHosts: _sourceHosts,
      plugins: _plugins,
      blockExtractors: _blocked,
      probeTimeout: _probeTimeout,
      ...remediaOptions
    } = this.options;

    try {
      this.remedia = await RemediaClient.create({
        ...remediaOptions,
        botUserId: clientId,

        selectNode: async (nodes, context) => {
          const queue = this.queues.get(context.guildId);

          if (!queue) {
            throw new Error(`No guild queue found for guild ID ${context.guildId}.`);
          }

          if (queue.options.selectNode) {
            return queue.options.selectNode(nodes, context);
          }

          const selected = nodes.length ? nodes[randomInt(nodes.length)] : undefined;

          if (!selected) {
            throw new Error(`No Remedia nodes are available for guild ID ${context.guildId}.`);
          }

          return selected.id;
        },
      });
      this.attachClientListeners(this.remedia);
    } catch (error) {
      this.#clientId = null;

      try {
        await this.plugins.destroy();
      } catch (cleanup) {
        throw new AggregateError([error, cleanup], 'Player initialization and plugin cleanup failed', {
          cause: cleanup,
        });
      }

      throw error;
    }
  }

  private attachClientListeners(client: RemediaClient): void {
    this.detachClientListeners?.();

    const cleanups: (() => void)[] = [];
    type ClientListener = <Name extends keyof RemediaClientEvents>(
      name: Name,
      handler: (...args: RemediaClientEvents[Name]) => void,
    ) => void;

    // Narrow Node's open EventEmitter overloads to the installed native contract.
    const subscribe = client.on.bind(client) as ClientListener;
    const unsubscribe = client.off.bind(client) as ClientListener;
    const on: ClientListener = (name, handler) => {
      subscribe(name, handler);
      cleanups.push(() => unsubscribe(name, handler));
    };
    const emit = this.emit.bind(this) as <Name extends keyof RemediaClientEvents>(
      name: Name,
      ...args: RemediaClientEvents[Name]
    ) => boolean;
    const forward = <Name extends keyof RemediaClientEvents>(name: Name) => {
      on(name, (...args) => emit(name, ...args));
    };

    for (const name of Object.values({ ...RemediaClientEventNames, ...PlaybackSessionEvents, ...VoiceSessionEvents })) {
      forward(name);
    }

    for (const name of ['sessionResumed', 'sessionLost'] as const) {
      on(name, (event) => {
        for (const guildId of event.guildIds) this.queues.get(guildId)?.emit(name, event);
      });
    }

    for (const name of ['guildAssigned', 'guildReleased'] as const) {
      on(name, (event) => this.queues.get(event.guildId)?.emit(name, event));
    }

    on('guildMigrated', (event) => this.queues.get(event.guildId)?.emit('guildMigrated', event));

    this.detachClientListeners = () => {
      for (const cleanup of cleanups) cleanup();
    };
  }

  /** Get the initialized Discord bot user ID.
   * @returns The bot's Discord user ID.
   */
  public getClientId(): string {
    if (!this.#clientId) {
      throw new Error('Player client ID is not initialized. Call player.initialize(clientId) first.');
    }

    return this.#clientId;
  }

  /** Forward Discord gateway voice payloads to Remedia.
   * @param payload Raw gateway packet from the Discord client's event adapter.
   */
  public receive(
    /** Raw gateway packet from the Discord client's event adapter. */
    payload: Record<string, unknown>,
  ): void {
    if (!this.remedia || typeof payload.t !== 'string') {
      return;
    }

    if (payload.t !== 'VOICE_STATE_UPDATE' && payload.t !== 'VOICE_SERVER_UPDATE') {
      return;
    }

    this.remedia.receive(payload);
  }

  /** Convert a supported in-memory media object to a SearchResult. Search strings require a source plugin.
   * @param query Track, Playlist, SearchResult, Track array, or query string.
   * @param options Source targeting, requester, and cancellation.
   * @returns A SearchResult, empty when no source plugin handled a query string.
   */
  public async search(
    /** Track, Playlist, SearchResult, Track array, or query string. */
    query: MediaResource,
    /** Source targeting, requester, and cancellation. */
    options: SearchOptions = {},
  ): Promise<SearchResult> {
    options.signal?.throwIfAborted();

    if (typeof query === 'string') await this.initialPlugins;

    if (typeof query !== 'string') return this.sources.search(query, options);

    if (!options.hostId) {
      const local = await this.sources.search(query, options);

      if (!local.isEmpty()) return local;
    }

    return (
      (await this.remoteSources.search(query, options, this.options.blockExtractors ?? [])) ??
      this.sources.search([], options)
    );
  }

  /** Select a source for the assigned audio node without opening remote media in the bot.
   * @internal
   * @param track Queued canonical Track.
   * @param nodeId Assigned Remedia node ID.
   * @param signal Playback preparation lifetime.
   * @returns Native operation descriptor for remote hosts, otherwise the local resolver result.
   */
  public async resolvePlaybackSource(track: Track, nodeId: string | null, signal: AbortSignal): Promise<MediaSource> {
    signal.throwIfAborted();

    const node = this.getRemedia().nodes.find((item) => item.id === nodeId);
    const hostId = track.sourceReference?.hostId;

    if (hostId) {
      this.remoteSources.assert(hostId);

      if (!track.sourceReference?.pluginId) throw new Error('Remote Track has no provider identity');

      if (this.options.blockExtractors?.includes(track.sourceReference.pluginId))
        throw new Error('Track provider is blocked');

      if (
        node?.type !== 'remote' ||
        !node.capabilities?.pluginOperations?.available ||
        !node.capabilities.pluginOperations.hosts.includes(hostId)
      )
        throw new Error(`Remedia node ${nodeId} cannot access source host ${hostId}`);

      const source: OperationMediaSource = {
        hostId,
        pluginId: SOURCE_PLUGIN_ID,
        operation: 'source.stream',
        input: { track: serializeSourceTrack(track) },
      };

      return source;
    }

    return this.plugins.resolveStream(track, {
      signal,
      remote: node?.type === 'remote',
      blocked: this.options.blockExtractors,
    });
  }

  /** Resolve a structural channel, create its guild queue, and delegate playback to `queue.play()`.
   * @param channel Voice channel object, channel ID, or explicit `{guildId, channelId}` pair.
   * @param resource Resource to search or play.
   * @param options Queue defaults and queue-managed playback options.
   * @returns The queue, selected Track, immediate Remedia result, and search result.
   */
  public async play<Metadata = unknown>(
    /** Voice channel object, channel ID, or explicit `{guildId, channelId}` pair. */
    channel: PlayerChannelResolvable,
    /** Resource to search or play. */
    resource: MediaResource,
    /** Queue defaults and queue-managed playback options. */
    options: PlayerPlayOptions<Metadata> = {},
  ): Promise<PlayerNodeInitializationResult<Metadata>> {
    const channelId = typeof channel === 'string' ? channel : 'channelId' in channel ? channel.channelId : channel.id;
    const inferredGuildId =
      typeof channel === 'string'
        ? undefined
        : 'channelId' in channel
          ? channel.guildId
          : (channel.guildId ?? channel.guild?.id);
    const guildId = options.guildId ?? inferredGuildId;

    if (!guildId) {
      throw new TypeError('A guildId is required when channel does not expose a structural guild reference.');
    }

    const queueDefaults = options.nodeOptions ?? options.queueOptions ?? {};
    const queue = await this.queues.create<Metadata>(guildId, queueDefaults);
    const searchResult = await this.search(resource, options.searchOptions);

    if (searchResult.isEmpty()) {
      return { queue, resource, searchResult, track: null, playerResult: null };
    }

    const {
      nodeOptions: _nodeOptions,
      queueOptions: _queueOptions,
      searchOptions: _searchOptions,
      guildId: _guildId,
      ...playOptions
    } = options;
    const result = await queue.play(searchResult, {
      ...playOptions,
      channelId,
    });

    return { queue, resource, searchResult, ...result };
  }

  /** Get an existing guild queue.
   * @param guildId Guild ID to resolve.
   * @returns The cached queue, or null when no queue exists.
   */
  public getQueue<Metadata = unknown>(
    /** Guild ID to resolve. */
    guildId: string,
  ) {
    return this.queues.get<Metadata>(guildId);
  }

  /** Get or create a guild queue.
   * @param guildId Guild ID to resolve.
   * @param options Queue defaults used only when the queue is first created.
   * @returns The existing or newly created queue.
   */
  public createQueue<Metadata = unknown>(
    /** Guild ID to resolve. */
    guildId: string,
    /** Queue defaults used only when the queue is first created. */
    options: GuildQueueOptions<Metadata> = {},
  ) {
    return this.queues.create(guildId, options);
  }

  /** Destroy this Player's queue for a guild ID.
   * @param guildId Guild ID whose queue should be destroyed.
   * @returns Whether a cached queue existed and was destroyed.
   */
  public deleteQueue(
    /** Guild ID whose queue should be destroyed. */
    guildId: string,
  ): Promise<boolean> {
    return this.queues.delete(guildId);
  }

  /** Abort the Player lifetime signal, then destroy all managed queues and plugins. */
  public async destroy(): Promise<void> {
    this.#lifetimeController.abort();
    unregisterPlayer(this);
    this.detachClientListeners?.();
    this.detachClientListeners = null;
    this.remoteSources.destroy();

    try {
      await this.queues.clear();
    } finally {
      await this.plugins.destroy();
    }
  }

  /** Emit a Player-level debug message.
   * @param message Message to publish.
   */
  public debug(
    /** Message to publish. */
    message: string,
  ): void {
    this.emit('debug', message);
  }
}

/** Compatibility alias retaining the v7 familiar `Player` class export. */
export { DiscordPlayer as Player };
